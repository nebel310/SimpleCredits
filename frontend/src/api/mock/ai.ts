const STAGES = ['Шансы', 'Заявка', 'Проверка', 'Решение', 'Подписание', 'Выдача'];
export function stageIndex(status?: string) {
  if (!status) return 0;
  if (status === 'DRAFT') return 1;
  if (['SUBMITTED', 'CHECKS', 'WAITING_SOURCE', 'SCORING', 'MANUAL_REVIEW', 'DOCS_REQUESTED', 'DOCS_REVIEW'].includes(status)) return 2;
  if (['OFFER', 'DECLINED', 'OFFER_REJECTED', 'EXPIRED'].includes(status)) return 3;
  if (status === 'SIGNING') return 4;
  return 5;
}

interface Input {
  user: User;
  ctx: AiContext;
  question: string;
  app?: ApplicationView;
  company?: Company;
  chances?: ChancesResult;
  profile?: Profile;
  bkiConsent: boolean;
}

export function answerQuestion(i: Input): AiAnswer {
  const q = i.question.toLowerCase().trim();
  const app = i.app;
  const appSrc = app ? [{ name: `Заявка № ${app.number}`, asOf: d(app.updatedAt) }] : [];
  const isClient = !isBankRole(i.user.role);

  // Режим 3: по шагам
  if (q === '__steps__') {
    const idx = stageIndex(app?.status);
    const st = app ? STATUS_PLAIN[app.status] : undefined;
    const lines = STAGES.map((s, n) => `${n < idx ? '✓' : n === idx ? '→' : '·'} ${s}`).join('\n');
    const actions: AiAnswer['actions'] = [];
    if (!app) actions.push({ label: 'Начать заявку', to: '/apply/goal' });
    else if (app.status === 'DOCS_REQUESTED') actions.push({ label: 'Открыть запрос', to: `/applications/${app.id}/documents` });
    else if (app.status === 'OFFER' || app.status === 'DECLINED') actions.push({ label: 'Посмотреть решение', to: `/applications/${app.id}/decision` });
    else if (app.status === 'SIGNING') actions.push({ label: 'Перейти к подписанию', to: `/applications/${app.id}/sign` });
    else if (app.status === 'DRAFT') actions.push({ label: 'Продолжить заявку', to: '/apply/goal' });
    return {
      ok: true,
      text: `Ваш путь к кредиту:\n${lines}\n\nСейчас: ${st ? st.now : 'вы смотрите предварительные шансы'}.\nЧто делать: ${st ? st.you : 'выберите продукт и начните заявку'}.`,
      sources: appSrc.length ? appSrc : [{ name: 'Кабинет', asOf: d(new Date().toISOString()) }],
      actions,
    };
  }

  // Ограничения роли
  if (i.user.role === 'viewer' && /документ|выписк|файл/.test(q)) {
    return { ok: true, limited: true, text: 'Документы заявки видят владелец и бухгалтер. Вам как наблюдателю доступны статус заявки, события и решение банка.', sources: appSrc };
  }
  if (i.user.role === 'accountant' && /подпис|принять предлож|принять услов/.test(q)) {
    return { ok: true, limited: true, text: 'Подписать договор и принять предложение может только владелец (руководитель). Вы можете подготовить данные и документы — владелец увидит задачу в своём кабинете.', sources: appSrc };
  }

  // Режим 1: выделить и спросить
  if (i.ctx.selection) {
    const sel = i.ctx.selection.trim();
    const g = findGlossary(sel) ?? findGlossary(q);
    if (g) {
      let extra = '';
      if (g.title.startsWith('Запас') && app?.afford && app.offer) {
        const pay = app.offer.monthlyPayment;
        const ds = app.afford.cashFlow / (app.afford.currentPayments + pay);
        extra = `\n\nНа ваших цифрах: денежный поток ${fmt(app.afford.cashFlow)} ₽ в месяц, платежи по кредитам сейчас ${fmt(app.afford.currentPayments)} ₽, новый платёж ${fmt(pay)} ₽. Запас получается ${ds.toFixed(2).replace('.', ',')}.`;
      }
      if (g.title === 'Долговая нагрузка' && i.profile && i.bkiConsent) {
        extra = `\n\nУ вас сейчас: платежи ${fmt(i.profile.currentPayments)} ₽ в месяц — это ${((i.profile.currentPayments / i.profile.cashFlow) * 100).toFixed(1).replace('.', ',')}% денежного потока. В правилах прототипа ориентир — не больше 35%.`;
      }
      return {
        ok: true,
        text: `«${sel.length > 60 ? sel.slice(0, 60) + '…' : sel}» — ${g.title.toLowerCase()}.\n\n${g.text}${extra}`,
        sources: extra ? [...appSrc, { name: 'Выписка по счёту и БКИ', asOf: d(new Date().toISOString()) }] : [{ name: 'Справочник терминов кабинета' }],
      };
    }
    const money = sel.match(/[\d\s]{4,}₽/);
    if (money) {
      return { ok: true, text: `«${sel}» — это сумма из раздела «${i.ctx.screen}». Если не понятно, откуда она взялась, спросите своими словами — например: «как посчитан платёж?»`, sources: appSrc };
    }
    return { ok: true, text: `Не нашёл точного объяснения для «${sel.slice(0, 50)}». Спросите своими словами — например: «что значит …» или «что мне сейчас делать?»`, sources: [] };
  }

  // Режим 2: свободный вопрос
  const g = findGlossary(q);
  if (/^(что такое|что значит|кто такой|объясни)/.test(q) && g) {
    return { ok: true, text: `${g.title}. ${g.text}`, sources: [{ name: 'Справочник терминов кабинета' }] };
  }

  if (/(это отказ|почему жд|что сейчас|что происходит|сколько жд|долго|статус)/.test(q)) {
    if (!app) return { ok: true, text: 'У вас пока нет отправленной заявки. На главной видно предварительные шансы по каждому продукту — с них удобно начать.', sources: [], actions: [{ label: 'Начать заявку', to: '/apply/goal' }] };
    const st = STATUS_PLAIN[app.status];
    const waiting = app.status === 'WAITING_SOURCE' && app.waitingFor ? ` Сейчас ждём ответ: ${app.waitingFor === 'bki' ? 'бюро кредитных историй' : app.waitingFor}.` : '';
    return {
      ok: true,
      text: `${st.now}.${waiting}\nКто сейчас работает: ${st.who}.\nЧто нужно от вас: ${st.you}.\n\nТочный срок для ручных и внешних проверок назвать не могу — статус обновится в кабинете сам, писем и SMS не будет.`,
      sources: appSrc,
    };
  }

  if (/почему.*(шанс|процент|оценк)|шанс/.test(q) && i.chances) {
    const neg = i.chances.factors.filter((f) => f.dir === '-');
    const unk = i.chances.factors.filter((f) => f.dir === '?');
    return {
      ok: true,
      text: `Шансы — предварительная модельная оценка, не гарантия одобрения. Что влияет сейчас:\n${neg.map((f) => `— ${f.name}: ${f.note}`).join('\n') || '— заметных минусов нет'}${unk.length ? `\nЕщё не учтено: ${unk.map((f) => f.name.toLowerCase()).join(', ')}.` : ''}\n\nЧто можно сделать: ${i.chances.recommendations[0]?.title ?? 'подать заявку'}.`,
      sources: i.chances.factors.filter((f) => f.asOf).slice(0, 3).map((f) => ({ name: f.source, asOf: d(f.asOf) })),
    };
  }

  if (/почему.*(отказ|не одобр)|причин/.test(q) && app?.decision) {
    return {
      ok: true,
      text: `Причины в решении банка:\n${app.decision.reasons.map((r) => `— ${r.plain}`).join('\n') || '— причины не указаны'}\n\nРешение принимает банк по правилам, я только объясняю. ${app.decision.advice.length ? 'Что можно сделать: ' + app.decision.advice[0] : ''}`,
      sources: [{ name: `Решение по заявке № ${app.number}`, asOf: d(app.decision.at) }],
    };
  }

  if (/(измен|другие условия|меньше|почему.*сумм)/.test(q) && app?.offer) {
    const o = app.offer;
    const r = o.requested;
    return {
      ok: true,
      text: `Вы просили ${fmt(r.amount)} ₽ на ${r.termMonths} мес, банк предлагает ${fmt(o.amount)} ₽ на ${o.termMonths} мес.${app.decision?.reasons.length ? ` Причина: ${app.decision.reasons.map((x) => x.plain.toLowerCase()).join('; ')}.` : ''}${app.afford ? ` При ${fmt(o.amount)} ₽ платёж ${fmt(o.monthlyPayment)} ₽ — денег бизнеса на него хватает с запасом.` : ''}\n\nМожно принять, отказаться или подать новую заявку позже.`,
      sources: [{ name: `Предложение банка, версия ${o.version}`, asOf: d(app.decision?.at) }],
    };
  }

  if (/(документ|выписк|что загруз|какие нужн)/.test(q)) {
    if (app?.documents.length) {
      const open = app.documents.filter((x) => !['accepted'].includes(x.status));
      return { ok: true, text: open.length ? `Банк просит:\n${open.map((x) => `— ${x.title} до ${d(x.deadline)}: ${x.why}`).join('\n')}\n\nПодойдут форматы ${open[0].formats.join(', ')}, до ${open[0].maxSizeMb} МБ.` : 'Все запрошенные документы приняты.', sources: appSrc, actions: open.length ? [{ label: 'Открыть запрос', to: `/applications/${app.id}/documents` }] : [] };
    }
    return { ok: true, text: 'Для заявки обычно ничего не нужно: данные о компании и выручке банк берёт из ФНС и выписки по вашему счёту. Иногда банк просит выписку из другого банка — тогда в кабинете появится запрос.', sources: [{ name: 'Правила кабинета' }] };
  }

  if (/(подпис|договор)/.test(q)) {
    if (!isClient) return { ok: true, text: 'Договор подписывает клиент в своём кабинете. Статус подписи виден на вкладке «Обзор».', sources: appSrc };
    return { ok: true, text: `Договор подписывает владелец (руководитель) электронной подписью прямо в кабинете.${app?.offer ? ` Условия — из принятой версии предложения: ${fmt(app.offer.amount)} ₽ на ${app.offer.termMonths} мес, ставка ${app.offer.ratePct}% годовых (модельная).` : ''} После подписи банк готовит перечисление.`, sources: appSrc };
  }

  if (/(ставк|стоимост|сколько стоит|переплат|комисси)/.test(q)) {
    const p = app?.offer ? productByCode(app.offer.product) : undefined;
    return { ok: true, text: p && app?.offer ? `${p.name}: ставка ${app.offer.ratePct}% годовых (модельная, для прототипа). Переплата за весь срок ≈ ${fmt(app.offer.overpayment)} ₽, комиссии: ${app.offer.fees.map((f) => `${f.name.toLowerCase()} ${fmt(f.amount)} ₽`).join(', ')}.` : 'У каждого продукта своя модельная ставка: оборотный кредит — 24%, овердрафт — 27% только за дни использования, кредит на развитие — 21% годовых. Это демо-значения, не реальные тарифы.', sources: [{ name: 'Тарифы прототипа' }] };
  }

  if (/(какую сумм|сколько взять|сумм)/.test(q) && i.profile) {
    const pay = Math.max(0, i.profile.cashFlow / 1.5 - i.profile.currentPayments);
    return { ok: true, text: `По вашим оборотам комфортный платёж — до ${fmt(pay)} ₽ в месяц: так денег хватит на кредит с запасом. Можно запросить и больше — банк рассмотрит запрос и сообщит доступные условия.`, sources: [{ name: 'Выписка по вашему счёту, среднее за 3 месяца', asOf: d(new Date().toISOString()) }] };
  }

  if (/(одобр|точно дадут|гарант)/.test(q)) {
    return { ok: true, text: 'Гарантировать одобрение не могу — решение принимает банк по правилам и проверкам. Могу объяснить, что влияет на оценку, и подсказать, что улучшить.', sources: [] };
  }

  if (g) return { ok: true, text: `${g.title}. ${g.text}`, sources: [{ name: 'Справочник терминов кабинета' }] };

  return {
    ok: true,
    text: 'Пока не знаю точного ответа на этот вопрос. Я могу объяснить термины, статус заявки, причины решения, условия предложения и какие нужны документы. Попробуйте спросить иначе или выделите непонятный текст на странице.',
    sources: [],
  };
}

export function draftDecisionText(outcome: DecisionInput['outcome'], reasons: string[], amount: number, app: { amount: number; termMonths: number }): string {
  const plain = reasons.map((r) => REASONS[r]?.plain).filter(Boolean) as string[];
  switch (outcome) {
    case 'APPROVE':
      return `Банк одобрил заявку: ${fmt(amount)} ₽ на ${app.termMonths} мес. Проверьте условия и подпишите договор в кабинете.`;
    case 'COUNTER_OFFER':
      return `Мы готовы выдать ${fmt(amount)} ₽ вместо ${fmt(app.amount)} ₽.${plain.length ? ' Почему: ' + plain.join('; ').toLowerCase() + '.' : ''} Если согласны — примите предложение и подпишите договор в кабинете.`;
    case 'REQUEST_DOCS':
      return `Чтобы принять решение, нам нужен документ.${plain.length ? ' Причина: ' + plain.join('; ').toLowerCase() + '.' : ''} Это не отказ — после проверки рассмотрение продолжится.`;
    default:
      return `По текущим данным банк не может выдать кредит.${plain.length ? ' Причины: ' + plain.join('; ').toLowerCase() + '.' : ''} Это решение по текущим данным: когда причины уйдут, можно подать заявку снова.`;
  }
}
